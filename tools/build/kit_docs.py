def mock(dark):
    """A docs page mock-up, 1280 x 800: header with the lockup and the strip, sidebar, article with heading, text, code and a note."""
    t = theme(dark); w, h = 1280, 800
    bg, surf, rule, fg, mut, link = (VOID, ABYSS, GRAPHITE, PAPER, HAZE, O_BLUE) if dark else (PAPER, WHITE, MIST, VOID, SLATE, ION)
    a = art_horizontal(); k = 26 / a.h
    ldefs, lg = a.place(t["mode"], "dl", 32, 19, k)
    s = svg_open(w, h, f"FusionSpace docs theme preview ({'dark' if dark else 'light'})", page=bg)
    s += f'<defs id="defs">{ldefs}{gradient("ds", 0, w)}</defs>\n'
    body = (f'<rect width="{w}" height="{h}" fill="{bg}"/><rect width="{w}" height="64" fill="{surf}"/><rect y="64" width="{w}" height="3" fill="url(#ds)"/>'
            + lg + text(w - 32, 40, "Search", 14, mut, family="sans", anchor="end")
            + f'<path d="M260,67V{h}" stroke="{rule}"/>')
    nav = ["Getting started", "Hardware", "Flight software", "Telemetry", "Ground station", "Reference"]
    for i, n in enumerate(nav):
        on = i == 2
        if on: body += f'<rect x="20" y="{104 + i * 38}" width="220" height="30" rx="4" fill="{surf}"/>'
        body += text(36, 124 + i * 38, n, 15, link if on else fg, family="sans", weight=600 if on else 400)
    x = 320
    body += text(x, 140, "FS-VEGA · EMB", 13, link, spacing=1.5)
    body += text(x, 186, "Flight software", 36, fg, weight=600)
    for i, l in enumerate(["The flight computer runs a fixed 100 Hz loop: read the IMU and barometer, update the state",
                           "estimate, then step the event state machine. Deployment events latch and are logged with the",
                           "loop counter, so a ground test reproduces the flight timeline exactly."]):
        body += text(x, 232 + i * 26, l, 16, fg, family="sans")
    body += f'<rect x="{x}" y="320" width="880" height="150" rx="4" fill="{surf}" stroke="{rule}"/>'
    code = [("void", link), (" loop_step(state_t *s) {", fg)], [("    imu_read", fg), ("(&s->imu);", fg)], [("    baro_read", fg), ("(&s->baro);", fg)], \
           [("    ekf_update", fg), ("(s, ", fg), ("0.01f", M_ORANGE if dark else EMBER), (");", fg)], [("}", fg)]
    esc = lambda z: z.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    for i, parts in enumerate(code):
        spans = "".join(f'<tspan fill="{c}">{esc(seg)}</tspan>' for seg, c in parts)
        body += (f'<text xml:space="preserve" x="{x + 24}" y="{352 + i * 24}" style="font-family:\'Cascadia Mono\',monospace;font-size:15px">{spans}</text>\n')
    body += text(x, 522, "Parameters", 24, fg, weight=600)
    body += f'<rect x="{x}" y="546" width="880" height="80" rx="4" fill="{surf}"/><rect x="{x}" y="546" width="4" height="80" fill="{M_ORANGE if dark else EMBER}"/>'
    body += text(x + 24, 576, "Note", 14, M_ORANGE if dark else EMBER, weight=600)
    body += text(x + 24, 604, "Apogee detection waits for three falling baro samples in a row.", 16, fg, family="sans")
    body += (f'<text xml:space="preserve" x="{x}" y="672" fill="{fg}" style="font-family:Archivo,sans-serif;font-size:16px">See <tspan fill="{link}">Telemetry</tspan> for the packet layout.</text>\n')
    return s + layer("Mock-up", body + "\n") + "</svg>\n"

def build_docs():
    D = f"{KIT}/software/docs-theme"; G = "Software & terminal"
    build.wr(f"{D}/mkdocs/fusionspace.css", MKDOCS_CSS); build.wr(f"{D}/mkdocs/mkdocs.yml", MKDOCS_YML)
    build.wr(f"{D}/docusaurus/custom.css", DOCUSAURUS_CSS)
    for dark in (True, False):
        tone = "dark" if dark else "light"
        src = save_svg(f"{D}/docs-preview-{tone}.svg", mock(dark)); png(src, f"{D}/docs-preview-{tone}.png", 1280, 800)
        import os; os.remove(src)
    build.wr(f"{D}/README.md", """# FusionSpace docs-site themes

- **MkDocs Material**: copy `mkdocs/fusionspace.css` to `docs/stylesheets/`, `type/fonts/*.ttf` to `docs/fonts/`, and merge
  `mkdocs/mkdocs.yml` into your config (light/dark palettes follow the reader's system setting).
- **Docusaurus**: use `docusaurus/custom.css` as `src/css/custom.css`; put the fonts in `static/fonts/` and change `../fonts/`
  to `/fonts/`. Set the navbar logo to `kit/web/favicon.svg`.

Both apply the brand tokens: Paper/Void pages, white/Abyss surfaces, Ion (light) and O blue (dark) links, Archivo body text,
Cascadia Mono headings and code, and the Fusion gradient as a 3 px line under the header. `docs-preview-*.png` show the look.
""")
    note(f"{D}/mkdocs/", G, "MkDocs Material theme (CSS and mkdocs.yml snippet)", "", "Project documentation sites")
    note(f"{D}/docusaurus/custom.css", G, "Docusaurus theme (custom.css)", "", "Project documentation sites")
    note(f"{D}/docs-preview-{{dark,light}}.png", G, "what a docs page looks like with the theme (drawn mock-up)", "1280 × 800", "Checking the look")
