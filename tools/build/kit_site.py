"""FusionSpace kit: drop-in files for fusionspace.co (kit/web/site/).

The site is a Next.js app (App Router file conventions: app/icon.svg, app/apple-icon.png, public/manifest.webmanifest,
public/og.png). This folder holds Rev C replacements for what the site serves today, plus a metadata snippet. Nothing here
touches the site; copy the files over by hand.

What the site served when it was checked from outside (SITE_CHECKED):
  icon.svg, apple-icon.png and og.png use the Rev B star cluster; /brand/fusion-space-wordmark.svg is the Rev B wordmark with
  the stars after it (Rev C allows the mark before the wordmark only); manifest lists one PNG per size as "any maskable";
  theme-color #ffffff (light) / #09090b (dark); name "Fusion Space" (two words) in <title>, og:title, application-name and
  the manifest; no /favicon.ico (404).
"""
import os, json, shutil
import build, kit
from kit import (KIT, note, out, save_svg, png, svg_open, layer, text, background, theme, art_horizontal, art_stacked, f,
                 VOID, PAPER, WHITE, SLATE, HAZE, ION, O_BLUE)

SITE_CHECKED = "2 October 2026"
NAME = "FusionSpace"     # one word, like the wordmark, everywhere (Neer; the site says "Fusion Space" today)

def metadata_ts(name):
    return f'''// FusionSpace metadata for the Next.js App Router (app/layout.tsx). Generated by tools/build/kit_site.py.
// Rev C icons and colours; copy the files in this folder first (see README.md).
import type {{ Metadata, Viewport }} from "next";

const NAME = "{name}";   // always one word, like the wordmark. The site says "Fusion Space" today: change its body copy too.
const DESCRIPTION = `${{NAME}} builds free, polished tools for the high-power rocketry community. Home of the HPR Motor Finder, with more rocketry tools on the way.`;

export const metadata: Metadata = {{
  metadataBase: new URL("https://fusionspace.co"),
  title: {{ default: NAME, template: `%s · ${{NAME}}` }},
  description: DESCRIPTION,
  applicationName: NAME,
  manifest: "/manifest.webmanifest",
  // app/icon.svg and app/apple-icon.png are picked up automatically; favicon.ico goes in app/ as well.
  openGraph: {{ title: NAME, description: DESCRIPTION, url: "/", siteName: NAME, type: "website",
                images: [{{ url: "/og.png", width: 1200, height: 630, alt: NAME }}] }},
  twitter: {{ card: "summary_large_image", title: NAME, description: DESCRIPTION, images: ["/og.png"] }},
}};

export const viewport: Viewport = {{
  // Brand Paper and Void. If the site keeps a pure white light theme, use "#ffffff" for the light entry.
  themeColor: [
    {{ media: "(prefers-color-scheme: light)", color: "{PAPER}" }},
    {{ media: "(prefers-color-scheme: dark)", color: "{VOID}" }},
  ],
  colorScheme: "light dark",
}};
'''

def build_site():
    D = f"{KIT}/web/site"; W = f"{KIT}/web"; G = "Website (fusionspace.co)"
    os.makedirs(out(f"{D}/app"), exist_ok=True); os.makedirs(out(f"{D}/public/brand"), exist_ok=True)
    # app/: icons Next picks up by file name
    for src, dst in (("favicon.svg", "app/icon.svg"), ("apple-touch-icon.png", "app/apple-icon.png"), ("favicon.ico", "app/favicon.ico")):
        shutil.copy(out(f"{W}/{src}"), out(f"{D}/{dst}"))
    # public/: manifest icons (separate "any" and "maskable"), header logo, link preview
    for z in (192, 512):
        shutil.copy(out(f"{W}/icon-{z}.png"), out(f"{D}/public/icon-{z}.png"))
        shutil.copy(out(f"{W}/icon-maskable-{z}.png"), out(f"{D}/public/icon-maskable-{z}.png"))
    man = {"name": NAME, "short_name": NAME, "description": "Free, polished tools for the high-power rocketry community.",
           "id": "/", "start_url": "/", "scope": "/", "display": "standalone", "background_color": VOID, "theme_color": VOID,
           "icons": [{"src": "/icon.svg", "sizes": "any", "type": "image/svg+xml", "purpose": "any"},
                     {"src": "/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
                     {"src": "/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
                     {"src": "/icon-maskable-192.png", "sizes": "192x192", "type": "image/png", "purpose": "maskable"},
                     {"src": "/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}]}
    build.wr(f"{D}/public/manifest.webmanifest", json.dumps(man, indent=2) + "\n")
    build.wr(f"{D}/metadata.ts", metadata_ts(NAME))
    assert " " not in NAME and 'const NAME = "FusionSpace"' in metadata_ts(NAME), "the site name is one word"
    # header logo: the Rev C horizontal lockup (mark before the wordmark), same file name the site already loads
    shutil.copy(out("logo/lockup/fusion-space-horizontal-color.svg"), out(f"{D}/public/brand/fusion-space-wordmark.svg"))
    # link preview: the brand one (Neer: the tagline, not the site's headline)
    shutil.copy(out(f"{KIT}/social/og-image-dark.png"), out(f"{D}/public/og.png"))
    build.wr(f"{D}/README.md", f"""# fusionspace.co: Rev C files

Checked from outside on {SITE_CHECKED}. The site still serves the Rev B star cluster in its tab icon (`/icon.svg`), home-screen icon
(`/apple-icon.png`), link preview (`/og.png`) and header logo (`/brand/fusion-space-wordmark.svg`, which also puts the stars after
the wordmark; Rev C allows the mark before it only). Everything here is a drop-in replacement with the same file names.

| Copy | To | Replaces |
|---|---|---|
| `app/icon.svg` | `app/icon.svg` | Rev B stars favicon (Rev C: the cluster on a Void tile) |
| `app/apple-icon.png` | `app/apple-icon.png` | Rev B home-screen icon |
| `app/favicon.ico` | `app/favicon.ico` | nothing (`/favicon.ico` is a 404 today; some tools and old browsers ask for it) |
| `public/icon-192.png`, `public/icon-512.png`, `public/icon-maskable-*.png` | `public/` | the manifest icons (today one file is used as both "any" and "maskable", which crops badly on Android) |
| `public/brand/fusion-space-wordmark.svg` | `public/brand/` | the header logo (Rev C horizontal lockup, gradient) |
| `public/brand/logo-on-white@2x.png` | `public/brand/` | nothing: the email signature's logo, which loads from `https://fusionspace.co/brand/logo-on-white@2x.png` |
| `public/manifest.webmanifest` | `public/manifest.webmanifest` | the manifest (name FusionSpace, Void theme, separate any/maskable icons) |
| `metadata.ts` | merge into `app/layout.tsx` | title, Open Graph, theme colours (name FusionSpace) |
| `public/og.png` | `public/og.png` | the link preview: the stacked lockup with the brand line, {kit.TAGLINE} (the same image as `kit/social/og-image-dark.png`) |

The name is **FusionSpace**, one word like the wordmark, in the title, Open Graph, manifest and description. The site's body copy
still says "Fusion Space" in places; change those to one word too.

Colours: the site's theme colour is `#ffffff` / `#09090b` today; the brand's are Paper `{PAPER}` / Void `{VOID}` (set in
`metadata.ts`). The site's buttons use an indigo close to, but not the same as, brand Ion `{ION}`.
""")
    note(f"{D}/app/icon.svg", G, "site tab icon (Next.js app/icon.svg)", "vector", "fusionspace.co")
    note(f"{D}/app/apple-icon.png", G, "site home-screen icon (app/apple-icon.png)", "180", "fusionspace.co")
    note(f"{D}/app/favicon.ico", G, "site favicon.ico (missing today)", "16/32/48", "fusionspace.co")
    note(f"{D}/public/brand/fusion-space-wordmark.svg", G, "site header logo: Rev C horizontal lockup under the file name the site already uses", "vector", "fusionspace.co header")
    note(f"{D}/public/icon-*.png", G, "manifest icons, any and maskable", "192, 512", "fusionspace.co manifest")
    note(f"{D}/public/og.png", G, "link preview with the brand line (copy of kit/social/og-image-dark.png)", "1200 × 630", "fusionspace.co /og.png")
    note(f"{D}/public/manifest.webmanifest", G, "web app manifest, name FusionSpace", "", "fusionspace.co")
    note(f"{D}/metadata.ts", G, "Next.js metadata (title, Open Graph, theme colours), name FusionSpace", "", "fusionspace.co app/layout.tsx")
    note(f"{D}/README.md", G, "what to copy where, and what the site serves today", "", "fusionspace.co")
