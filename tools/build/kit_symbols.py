"""SF Symbols custom symbols from the product icons: product/icons/sf-symbols/FusionSpaceSymbols.xcassets.

product/mobile.md asks for the domain icons as custom symbols on iOS and watchOS, so they sit in tab bars, buttons and
labels next to SF Symbols, scale with Dynamic Type and take the platform's rendering modes. A custom symbol is a template
SVG with filled outlines (no strokes) on Apple's guides; this converts each 24 px icon's strokes to outlines (picosvg) and
places it as the Regular-S, Regular-M and Regular-L variants. Xcode draws the other weights from them (statically; the icons have one stroke
weight by design). Use: drag the .xcassets into a project, then `Image("fs.rocket")` or `Label("Pad", image: "fs.launch-rail")`.
"""
import os, json, shutil, subprocess
import build, kit_product as kp, kit_icons

DIR = "icons/sf-symbols"
CATALOG = "FusionSpaceSymbols.xcassets"
# Apple's template v3 guides (points at the template's 100 pt size); cap height 70.46. SF Symbols at Regular-M span about
# the margin guides' height (1030.79 to 1150.12, 119 units), well beyond the cap height; drawn at 90 units the icons came out
# at half the size of SF Symbols next to them (checked in a tab bar on the iOS 27 simulator). So the icon's 24 px box is
# drawn 118 units square, centered on the guides.
BASE_M, CAP_M = 1126.0, 1055.54
GUIDE_TOP, GUIDE_BOTTOM = 1030.79, 1150.12
BOX = 118.0
X0 = 1391.0

def outlines(name, k=1.0, dx=0.0, dy=0.0):
    """The icon's strokes as filled outline paths, scaled by k and moved by (dx, dy). The coordinates are written into the
    paths: Xcode ignores a transform on the symbol's group."""
    from picosvg.svg import SVG
    from picosvg.svg_transform import Affine2D
    t = Affine2D(k, 0, 0, k, dx, dy)
    return [s.apply_transform(t).round_floats(3).d for s in SVG.fromstring(kit_icons.svg(name, 24)).topicosvg().shapes()]

# The three scales, each on its own guides: (variant, baseline, capline, box height, left x). Small and large keep Apple's
# ratios to medium (about 0.78 and 1.29); without them a symbol asked for at .imageScale(.small) or .large draws nothing.
SCALES = [("Regular-S", 696.0, 625.541, BOX * 0.783, 1391.0), ("Regular-M", BASE_M, CAP_M, BOX, X0), ("Regular-L", 1556.0, 1485.54, BOX * 1.29, 1391.0)]

def template(name):
    guide = 'style="fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;"'
    lines = "".join(f'<line id="{i}" {guide} x1="263" x2="3036" y1="{y}" y2="{y}"/>' for i, y in
                    (("Baseline-S", 696), ("Capline-S", 625.541), ("Baseline-M", BASE_M), ("Capline-M", CAP_M),
                     ("Baseline-L", 1556), ("Capline-L", 1485.54)))
    margins, groups = "", ""
    for variant, base, cap, box, x0 in SCALES:
        k = box / 24
        # centered where medium is centered relative to its own baseline and cap line
        mid = (base + cap) / 2 + ((GUIDE_TOP + GUIDE_BOTTOM) / 2 - (BASE_M + CAP_M) / 2) * (box / BOX)
        ty = mid - 12 * k
        margins += (f'<line id="left-margin-{variant}" {guide} x1="{x0}" x2="{x0}" y1="{mid - box / 2:.2f}" y2="{mid + box / 2:.2f}"/>'
                    f'<line id="right-margin-{variant}" {guide} x1="{x0 + box:.2f}" x2="{x0 + box:.2f}" y1="{mid - box / 2:.2f}" y2="{mid + box / 2:.2f}"/>')
        paths = "".join(f'<path d="{d}"/>' for d in outlines(name, k, x0, ty))
        groups += f'<g id="{variant}">{paths}</g>'
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<!-- FusionSpace custom symbol "fs.{name}", from product/icons/{name}.svg. Generated by tools/build/kit_symbols.py. -->
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" width="3300" height="2200">
<g id="Notes"><text id="template-version" style="stroke:none;fill:black;font-family:sans-serif;font-size:13;" x="3036" y="1933">Template v.3.0</text></g>
<g id="Guides">{lines}{margins}</g>
<g id="Symbols">{groups}</g>
</svg>
'''

README = """# SF Symbols

Every icon in `product/icons/` as an SF Symbols custom symbol, named `fs.<icon>` (`fs.rocket`, `fs.launch-rail`,
`fs.flight-computer`), in one asset catalog, `FusionSpaceSymbols.xcassets`. Generated by `tools/build/kit_symbols.py`:
each icon's 1.5 px strokes are converted to outlines and placed as the template's Regular-S, -M and -L variants, on Apple's guides.

Drag the catalog into an iOS or watchOS target, then:

```swift
Image("fs.rocket")                                  // scales with the text style around it
Label("Pad", image: "fs.launch-rail")               // tab bars, lists, buttons
Tab("Track", image: "fs.gps-fix", value: .track)
```

Domain icons come from here; system actions (share, close, more) stay SF Symbols, as `product/mobile.md` says. The symbols
are static: one stroke weight by design, so a bold font doesn't thicken them. Each `.svg` also opens in the SF Symbols app.

Checked: the catalog compiles with Xcode 27's `actool` for iOS and watchOS with no warnings, and the sample app's tab bar
uses `fs.launch-rail`, `fs.gps-fix`, `fs.flight-log` and `fs.flight-computer` on the iOS 27 simulator
(`product/mobile/devices/`).
"""

def build_symbols():
    try:
        import picosvg  # noqa: F401
    except ImportError:
        print("WARN symbols: picosvg missing (pip install picosvg), SF Symbols skipped"); return
    cat = kp.out(f"{DIR}/{CATALOG}")
    if os.path.isdir(cat): shutil.rmtree(cat)
    os.makedirs(cat)
    info = {"info": {"author": "xcode", "version": 1}}
    with open(os.path.join(cat, "Contents.json"), "w") as fh: json.dump(info, fh, indent=2); fh.write("\n")
    for n in kit_icons.ICONS:
        sd = os.path.join(cat, f"fs.{n}.symbolset"); os.makedirs(sd)
        with open(os.path.join(sd, f"fs.{n}.svg"), "w", encoding="utf-8") as fh: fh.write(template(n))
        with open(os.path.join(sd, "Contents.json"), "w") as fh:
            json.dump({**info, "symbols": [{"filename": f"fs.{n}.svg", "idiom": "universal"}]}, fh, indent=2); fh.write("\n")
    kp.wr(f"{DIR}/README.md", README)
    # compile check when Xcode is installed: the build stops if actool rejects a symbol
    dev = "/Applications/Xcode.app/Contents/Developer"
    if os.path.isdir(dev):
        tmp = os.path.join(build.TMP, "actool"); os.makedirs(tmp, exist_ok=True)
        for plat in ("iphonesimulator", "watchsimulator"):
            r = subprocess.run(["xcrun", "actool", cat, "--compile", tmp, "--platform", plat, "--minimum-deployment-target", "26.0",
                                "--output-format", "human-readable-text", "--warnings", "--errors"],
                               capture_output=True, text=True, env={**os.environ, "DEVELOPER_DIR": dev})
            bad = [l for l in r.stdout.splitlines() + r.stderr.splitlines() if "warning" in l.lower() or "error" in l.lower()]
            if r.returncode or bad: raise SystemExit(f"SF Symbols ({plat}): actool says\n  " + "\n  ".join(bad or [r.stderr]))

if __name__ == "__main__":
    build_symbols()
